#!/usr/bin/env python3
"""Write raw/TRACE.md: for every source cited on the page (build/sources.json SRC) the raw files in raw/ that back it,
and for every dashboard row (MAP) the sources it cites. Run from the repo root."""
import csv, json
S = json.load(open('build/sources.json'))
SRC, MAP = S['SRC'], S['MAP']
man = list(csv.DictReader(open('raw/MANIFEST.csv', newline='')))
by_url = {}
for r in man: by_url.setdefault(r['source_url'], []).append(r)
def urls(s):
    u = []
    if 'm' in s: u += list(s['m'].values())
    if 'u' in s: u.append(s['u'])
    return u
EXTRA = {  # sources with no single URL list: where their raw files live
    'doe25': ['nh-doe25/'], 'ip': ['nh-doe/iplatform-extracts-2026-11-22.md', 'nh-doe/extracts-2026-11-22/'],
    'iplat': ['nh-doe/iplatform-extracts-2026-11-22.md', 'nh-doe/extracts-2026-11-22/'],
    'iach': ['nh-doe/dashboard-exports-2026-11-22/iexplore_compare_all_entities.tsv', 'nh-doe/extracts-2026-11-22/iexplore-school-level.py'],
    'irep': ['nh-doe/dashboard-exports-2026-11-22/ireport_essa_idea_suspension.tsv', 'nh-doe/extracts-2026-11-22/ireport-essa-ratings.txt'],
    'bls': ['bls/'], 'arv': ['orcsd/web/news_2026-03-10_official-voting-results.html'],
}
out = ['# Trace: page source to raw file', '',
       'Generated by `build/gen_trace.py` from `build/sources.json` and `raw/MANIFEST.csv`. Paths are under `raw/`.',
       'Status per source: **file** = the original file is in `raw/`; **mixed** = some years are files, some are not; '
       '**export** = raw worksheet export of a live dashboard; **transcribed** = values copied from a live report viewer that offers no download.', '']
out += ['## Sources', '', '| Source key | What | Raw files |', '|---|---|---|']
for k, s in SRC.items():
    u = urls(s); files = sorted({r['stored_as'] for x in u for r in by_url.get(x, [])})
    missing = [x for x in u if x not in by_url]
    files += EXTRA.get(k, [])
    note = ''
    if u: note = f' ({len(u)-len(missing)}/{len(u)} URLs mirrored)'
    if not files: note += ' NO RAW FILE'
    loc = ', '.join(f'`{f}`' for f in files[:4]) + (f' +{len(files)-4} more' if len(files) > 4 else '')
    out.append(f"| `{k}` | {s['n']} | {loc or '-'}{note} |")
out += ['', '## Dashboard rows', '', '| Row key | Sources cited |', '|---|---|']
for k, v in MAP.items(): out.append(f"| `{k}` | {', '.join('`'+x+'`' for x in v)} |")
out += ['', '## Gaps and caveats', '',
 '- iPlatform reports (town enrollment by grade, FTE staff, student-teacher ratio 2022-26, class size, teacher salary and attainment 2023+, attendance by school, completers) offer no file download. Only the values read from the report viewer are kept (`nh-doe/iplatform-extracts-2026-11-22.md`, `nh-doe/extracts-2026-11-22/`). These are transcriptions, not original files.',
 '- iAchieve participation and graduation figures come from the iExplore export; values outside that export are transcribed.',
 '- `nh-doe/dashboard-exports-2026-11-22/ireport_essa_idea_suspension.tsv` has the suspension, expulsion and IDEA Indicator 5 worksheets. Its ESSA Indicators section carries only a header (that worksheet returned every NH school and was left out); ESSA ratings are instead backed by the iExplore export and checked by `build/verify_dashboard_values.py`.',
 '- FY26 and FY27 budget context also draws on `orcsd/board-packets/` and `orcsd/financial-reports/`, which are cited by URL on the page.',
 '- NH DOE assessment files for 2019-20 do not exist (no testing that spring).',
 '', 'Checks: `python3 build/verify_raw.py` (manifest, checksums, no unlisted files) and `python3 build/verify_dashboard_values.py` (transcribed school-level and ESSA values against the raw exports).']
open('raw/TRACE.md', 'w').write('\n'.join(out) + '\n')
print('\n'.join(l for l in out if 'NO RAW' in l or '/' not in l and 'mirrored' in l))
